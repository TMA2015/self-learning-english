'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {execFileSync}=require('node:child_process');
const root=path.resolve(__dirname,'..');
execFileSync(process.execPath,['node_modules/typescript/bin/tsc','domain/navigation-gate.ts','--outDir','.sites-runtime/v20-route-test','--module','commonjs','--target','es2022','--skipLibCheck'],{cwd:root,stdio:'inherit'});
fs.writeFileSync(path.join(root,'.sites-runtime/v20-route-test/package.json'),'{'+'"type":"commonjs"'+'}');
const {createNavigationGate,confirmLatestDraft}=require('../.sites-runtime/v20-route-test/navigation-gate.js');
const routePage=fs.readFileSync(path.join(root,'app/page.tsx'),'utf8');
const clientPath=path.join(root,'app/home-client.tsx');
const page=fs.readFileSync(fs.existsSync(clientPath)?clientPath:path.join(root,'app/page.tsx'),'utf8');
assert.ok(!fs.existsSync(clientPath)||routePage.includes('<HomeClient/>'),'static route wrapper must render HomeClient');
const player=fs.readFileSync(path.join(root,'app/foundation.tsx'),'utf8');
const nav=page.split('const navGroups=')[1]?.split('] as const;')[0];
assert.ok(nav,'all sidebar routes must be inspectable');
const routes=[...nav.matchAll(/key:"([^"]+)"/g)].map(m=>m[1]);
assert.ok(routes.includes('dashboard')&&routes.includes('parent')&&routes.includes('foundation')&&routes.includes('writing'),'required non-skill and skill routes missing');
assert.equal(new Set(routes).size,routes.length,'sidebar destinations must be unique');
assert.ok(page.includes('foundationNavigationGuard.current?.(target)'),'route waits for child guard');
assert.ok(page.includes('onNavigationGuard={registerFoundationNavigationGuard}'),'mounted Foundation player registers guard');
assert.ok(page.includes('disabled={navigating} onClick={()=>void navigate(n.key)}'),'all sidebar buttons use the guarded route');
assert.ok(player.includes('if(recordingNow||media.current?.state===\'recording\')'),'live microphone capture must block navigation');
assert.ok(player.includes('if(busy){setError('),'in-flight lesson actions must block navigation');
const guard=player.split('routeGuardRef.current=async target=>{')[1]?.split('\n };')[0];
assert.ok(guard&&guard.indexOf('await confirmLatestDraft(')<guard.indexOf('preparedSkillSwitch.current=target'),'route cannot change skills before server-confirmed save');
assert.ok(guard.includes('setError(\'Draft save failed. Stay on this lesson and retry.'),'failed saves have visible failure feedback');
const deferred=()=>{let resolve;const promise=new Promise(r=>resolve=r);return {promise,resolve}};
(async()=>{
 const pendingEdit=deferred();let revision=1,writes=[];
 const latest=confirmLatestDraft(()=>revision,async()=>{writes.push(revision);if(writes.length===1)await pendingEdit.promise});
 revision=2;pendingEdit.resolve();await latest;
 assert.deepEqual(writes,[1,2],'an edit made during a pending save must get its own confirmed write');
 let failures=0;
 await assert.rejects(confirmLatestDraft(()=>revision,async()=>{failures++;throw Error('server unavailable')}),/server unavailable/);
 await confirmLatestDraft(()=>revision,async()=>{failures++});
 assert.equal(failures,2,'a rejected save remains retryable');
 for(const route of routes){
  const gate=createNavigationGate(),pending=deferred(),committed=[];
  const first=gate(route,()=>pending.promise,value=>committed.push(value));
  const rapid=await gate('other',async()=>true,value=>committed.push(value));
  assert.equal(rapid,false,'rapid route must not overtake pending save: '+route);
  assert.deepEqual(committed,[],'route changed before server confirmation: '+route);
  pending.resolve(true);assert.equal(await first,true);assert.deepEqual(committed,[route]);
  const failed=await gate('other',async()=>false,value=>committed.push(value));
  assert.equal(failed,false);assert.deepEqual(committed,[route],'failed save navigated: '+route);
  const retry=await gate('other',async()=>true,value=>committed.push(value));
  assert.equal(retry,true);assert.deepEqual(committed,[route,'other'],'retry did not navigate after confirmation');
 }
 console.log('PASS: '+routes.length+' sidebar destinations wait for a save; rapid routes and failed saves stay put; retry succeeds.');
})().catch(e=>{console.error(e);process.exitCode=1});
