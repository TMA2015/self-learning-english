'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),{execFileSync}=require('node:child_process');
const root=path.resolve(__dirname,'..'),out=path.join(root,'.sites-runtime/w2-r2-qa');
execFileSync(process.execPath,[path.join(root,'node_modules/typescript/bin/tsc'),
 'domain/writing-course-v2-b.ts','--outDir',out,'--module','commonjs','--target','es2022',
 '--jsx','react-jsx','--resolveJsonModule','--esModuleInterop','--skipLibCheck'],
 {cwd:root,stdio:'inherit'});
fs.writeFileSync(path.join(out,'package.json'),'{"type":"commonjs"}');
const domainFile=fs.existsSync(path.join(out,'domain/writing-course-v2-b.js'))?'domain/writing-course-v2-b.js':'writing-course-v2-b.js';
const d=require(path.join(out,domainFile));
const w=d.writingWeek(2);
const keys=w.fields.map(f=>f.key);
assert.deepEqual(keys,['ideas','reject','best','fit'],'Canonical four-key schema');
assert.deepEqual(w.fields.filter(f=>f.required).map(f=>f.key),['ideas','best','fit'],'Reject optional only in Week 2');
for(let i=1;i<=4;i++)assert.equal(w.items[i-1].id,'WCV2-W2-G'+i);
const taskFields={ideas:'Drawing club\nMusic club\nScience club',best:'Drawing club',fit:'Students can work together and share ideas.'};
let draft={...d.emptyWeekWork(),fields:{...taskFields},confirmedOwnWork:true};
assert(d.completeWeek(2,draft),'Three required fields are sufficient');
assert.equal(d.weekStructureCheck(2,draft).length,3);
assert(d.weekStructureCheck(2,draft).every(x=>x.present));
const saved=d.submitWeek(2,draft,111);
assert.equal(saved.history.length,1);
assert.deepEqual(saved.history[0].fields,taskFields,'No invented rejection');
assert(d.canCompareWeek(2,saved,'review'),'Stored signature must be valid without reject');
assert(!d.completeWeek(2,{...draft,fields:{ideas:'',best:'Drawing club',fit:'Because...'}}));
assert(!d.completeWeek(2,{...draft,fields:{ideas:'Art',best:'',fit:'Because...'}}));
assert(!d.completeWeek(2,{...draft,fields:{ideas:'Art',best:'Art',fit:''}}));
assert(!d.completeWeek(2,{...draft,confirmedOwnWork:false}));
const validGuided=w.items.map((q,i)=>d.checkWeekGuided(2,[],q.id,q.correct,500+i));
assert.equal(d.weekGuidedProgress(2,validGuided).finished,4);
assert(!d.weekReviewReflectionReady(2,saved),'No reflection yet');
assert.throws(()=>d.finishWeekReview(2,{...saved,guided:validGuided}),/reflection/);
const reflected={...saved,guided:validGuided,reflections:{selection:'It fits the task and I can explain my reason.'}};
assert(d.weekReviewReflectionReady(2,reflected),'One R2 selection reflection');
assert(d.finishWeekReview(2,reflected).reviewDone,'One reflection is enough after guided and saved attempt');
assert.throws(()=>d.finishWeekReview(2,{...reflected,guided:validGuided.slice(1)}),/Guided Practice/);
assert.throws(()=>d.finishWeekReview(2,{...reflected,submission:undefined}),/complete attempt/);
const legacyFields={...taskFields,reject:'Change the uniform'};
const legacySaved=d.submitWeek(2,{...draft,fields:legacyFields},222);
const originalReflections={'0':'The task asks for an activity','1':'I rejected a uniform change','2':'Drawing club'};
const old={...legacySaved,guided:validGuided,reflections:originalReflections};
assert(d.weekReviewReflectionReady(2,old),'Full previous R1 reflections must remain valid');
const oldDone=d.finishWeekReview(2,old);
assert(oldDone.reviewDone);
assert.deepEqual(oldDone.reflections,originalReflections,'Old reflection keys/content unchanged');
assert.deepEqual(oldDone.history,legacySaved.history,'History unchanged');
assert.deepEqual(oldDone.history[0].fields,legacyFields,'Historical rejected idea retained');
const partialOld={...saved,guided:validGuided,reflections:{'0':'Legacy old prompt answer'}};
assert(!d.weekReviewReflectionReady(2,partialOld),'A partial legacy reflection must not be falsely complete');
const upgraded={...partialOld,reflections:{...partialOld.reflections,selection:'My explanation is clear.'}};
assert(d.finishWeekReview(2,upgraded).reviewDone);
assert.equal(upgraded.reflections['0'],'Legacy old prompt answer','Legacy partial text preserved');
const edited=d.editWeek(oldDone,'best','Music club');
assert.equal(edited.submission,undefined);
assert(!d.canCompareWeek(2,edited,'review'));
assert.deepEqual(edited.history,oldDone.history,'Revision cannot erase historic snapshot');
assert.equal(d.writingWeek(2).reflections.length,3,'Legacy labels preserved, not relabelled');
assert(!d.writingWeek(2).model.includes('I rejected'),'New model must not force a bad candidate');
const wk3=d.writingWeek(3);
assert.equal(wk3.fields.filter(x=>x.required).length,3,'Other weeks retain original required fields');
const wk3Draft={...d.emptyWeekWork(),fields:{opinion:'Yes',reason:'Students explore',matters:'They learn outdoors'},confirmedOwnWork:true};
const wk3Saved=d.submitWeek(3,wk3Draft,333);
const wk3Guided=wk3.items.map((q,i)=>d.checkWeekGuided(3,[],q.id,q.correct,600+i));
assert(!d.weekReviewReflectionReady(3,{...wk3Saved,guided:wk3Guided,reflections:{'0':'Only one'}}),'Week 3 still needs three reflections');
const text=fs.readFileSync(path.join(root,'app/writing-week2-course-simplified.tsx'),'utf8');
assert(text.includes('Your ideas have not been graded by AI or a teacher'));
assert(text.includes('Ideas I set aside: optional.'));
assert(text.includes("work.reflections[String(i)]"),'Legacy reflection display unchanged');
assert(!/fetch\s*\(|Gemini|GoogleAIBackend/.test(text),'No remote AI added by R2');
console.log(JSON.stringify({result:'PASS',gate:'W2_R2_OPTIONAL_REJECT_SINGLE_REFLECTION',
 canonicalKeys:4,requiredFields:3,reflectionRequired:1,
 legacyCompletedValid:true,legacyNotesBytePreserved:true,otherWeeksUnchanged:true,realAIRequests:0}));
