'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),{execFileSync}=require('node:child_process');
const root=path.resolve(__dirname,'..');
const compiled=path.join(root,'.sites-runtime/listening-completion-test');
execFileSync(process.execPath,['node_modules/typescript/bin/tsc','domain/listening-completeness.ts','--outDir',compiled,'--module','commonjs','--target','es2022','--skipLibCheck'],{cwd:root,stdio:'inherit'});
fs.writeFileSync(path.join(compiled,'package.json'),'{"type":"commonjs"}');
const {listeningCompletion,listeningSubmitHint}=require(path.join(compiled,'listening-completeness.js'));
const qs=[{id:'LIS-A2-01-Q1'},{id:'LIS-A2-01-Q2'},{id:'LIS-A2-01-Q3'}];
assert.deepEqual(listeningCompletion(qs,{}),{total:3,answered:0,unansweredIds:qs.map(q=>q.id)});
const partial=listeningCompletion(qs,{'LIS-A2-01-Q1':'A','LIS-A2-01-Q2':'  ','LIS-A2-01-Q3':'C'});
assert.deepEqual(partial,{total:3,answered:2,unansweredIds:['LIS-A2-01-Q2']});
assert.equal(listeningSubmitHint(partial),'2/3 answered · 1 question remaining.');
assert.equal(listeningSubmitHint(listeningCompletion(qs,{})),'0/3 answered · 3 questions remaining.');
const complete=listeningCompletion(qs,{'LIS-A2-01-Q1':'A','LIS-A2-01-Q2':'B','LIS-A2-01-Q3':'C'});
assert.deepEqual(complete.unansweredIds,[]);
assert.equal(listeningSubmitHint(complete),'3/3 answered · All questions answered.');
const player=fs.readFileSync(path.join(root,'app/foundation.tsx'),'utf8');
const css=fs.readFileSync(path.join(root,'app/globals.css'),'utf8');
const service=fs.readFileSync(path.join(root,'application/academic-service.ts'),'utf8');
const action=player.slice(player.indexOf('async function submit()'),player.indexOf('async function play()'));
assert.ok(action.includes("lesson.module==='listening'&&listeningProgress?.unansweredIds.length"),'client preflight scoped to Listening');
assert.ok(action.indexOf('unansweredIds.length')<action.indexOf('await saveDraft()'),'incomplete submit blocked before any submission call');
assert.ok(action.includes('setShowMissing(true)'),'unanswered items highlighted');
assert.ok(action.includes('scrollIntoView'),'first missing question brought into view on mobile');
assert.ok(action.includes("querySelector<HTMLInputElement|HTMLTextAreaElement>"),'first unanswered control receives focus');
assert.ok(action.includes("setSubmitError(message)"),'server/network submission errors visible at action area');
assert.ok(player.includes('foundation-listening-completion')&&player.includes('listeningSubmitHint(listeningProgress)'),'persistent completion status');
assert.ok(player.includes('foundation-question-warning')&&player.includes('foundation-submit-warning'),'inline missing-question warning');
assert.ok(player.includes('role="alert"')&&player.includes('aria-live="polite"'),'screen-reader announcements');
assert.ok(css.includes('.foundation-question.is-unanswered')&&css.includes('@media(max-width:600px)'),'mobile highlighted question');
assert.ok(service.includes("if(l.activities.some(q=>q.type!=='extended_response'?!a.answers[q.id]?.trim()"),'authoritative server validation remains');
assert.ok(service.includes("if(l.module==='listening'&&!a.playbackCompleted)"),'audio completion guard unchanged');
assert.ok(player.includes("setDraftFeedback({kind:'saved',at:Date.now()})"),'server-confirmed draft status preserved');
assert.ok(player.includes('await refresh();onEvidence?.()'),'normal successful score and refresh preserved');
console.log('PASS: blank and whitespace answers, inline Listening warning, mobile first-unanswered focus, unchanged server/audio/draft safeguards.');
