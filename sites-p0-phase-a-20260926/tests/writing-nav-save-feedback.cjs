"use strict";
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const page=read('app/page.tsx')+read('app/home-client.tsx'), player=read('app/foundation.tsx'), platform=read('app/platform.tsx'), css=read('app/globals.css');

assert.equal((page.match(/<WritingHome\b/g)||[]).length,1,'Writing Coach renders once');
assert.ok(page.includes('writingIntro={view==="writing"?<WritingHome compact'),'shared writing intro slot');
assert.ok(!page.includes('view==="writing"&&<WritingHome'),'no separate Writing section above the player');
assert.ok(platform.includes('compact=false'),'Writing Coach must retain standalone default');
assert.ok(platform.includes('{!compact&&<>'),'compact Writing Coach should not repeat heading');
assert.ok(player.includes('writingIntro?:ReactNode'),'optional slot must not affect other skills');
assert.ok(player.includes("screen==='catalog'&&(entryMode==='units'?<UnitBrowser")&&player.includes('foundation-writing-coach'),'Writing Coach remains exclusively in the skill-catalog branch, not the new Unit guide');
const pathTab=player.indexOf('className="foundation-path"');
const coach=player.indexOf('className="foundation-writing-coach"');
const recent=player.indexOf('foundation-recent"');
const catalog=player.indexOf('foundation-catalog-panel"');
assert.ok(pathTab>=0&&pathTab<coach&&coach<recent&&recent<catalog,'skill tabs before optional Writing Coach, recent work and catalog');
assert.ok(css.includes('.foundation-writing-coach{'),'Writing Coach wrapper styling');

assert.ok(player.includes("markDraftChanged();setAnswers(s=>({...s,[q.id]:o.id}))"),'MCQ updates dirty state');
assert.ok(player.includes("markDraftChanged();setAnswers(s=>({...s,[q.id]:e.target.value}))"),'text input updates dirty state');
assert.ok(player.includes("markDraftChanged();setRecording("),'audio recording updates dirty state');
assert.ok(player.includes("const task=draftSaveQueue.current.catch(()=>{}).then("),'save operations must be sequential');
assert.ok(player.includes("if(revision===draftRevision.current)setDraftFeedback({kind:'saved',at:Date.now()})"),'save confirmed only for latest revision after success');
assert.ok(player.includes("if(revision===draftRevision.current)setDraftFeedback({kind:'error'})"),'latest save failure stays visible');
assert.ok(player.includes('All changes saved'),'explicit confirmation');
assert.ok(player.includes('Saving draft…'),'saving state');
assert.ok(player.includes('Save failed · Retry save'),'failure state');
assert.ok(player.includes('Draft restored · saved previously'),'restoration state');
assert.ok(player.includes("draftFeedback.kind==='error'?'Retry save':'Save draft'"),'manual retry');
assert.ok(player.includes('role="status" aria-live="polite"'),'accessible status');
assert.ok(player.includes('aria-hidden="true">{draftSaveText}</p>'),'visible confirmation near Save draft button');
const editableStart=player.indexOf('{editable?<>');
const editableEnd=player.indexOf('aria-hidden="true">{draftSaveText}</p></>:<><p>{attempt.status',editableStart);
const editableActions=player.slice(editableStart,editableEnd);
assert.ok(editableStart>=0&&editableEnd>editableStart&&editableActions.includes('<div className="learning-choices">')&&editableActions.includes('Save draft')&&editableActions.includes('Submit my work'),'action and draft status still share the editable JSX fragment with optional Listening validation before actions');
assert.ok(player.includes('aria-hidden="true">{draftSaveText}</p></>:<><p>{attempt.status'),'editable JSX branch closes before read-only results');
assert.ok(css.includes('.foundation-draft-feedback.is-error'),'clear failure visual');

const transitions=player.split("useEffect(()=>{if(previousSkill.current===routeScope)")[1]?.split("},[routeScope]);")[0];
assert.ok(transitions,'pre-existing v14 skill guard retained');
assert.equal(transitions.split('void refresh().catch(').length-1,1,'nonblocking single Catalog refresh retained after draft save');
assert.equal(transitions.split('await refresh()').length-1,0,'do not block navigation on the optional catalog request');
assert.ok(player.includes('onSelectSkill?.(next)}'),'top skill cards use the parent draft-save gate');
assert.ok(player.includes('routeGuardRef.current=async target=>'),'parent route guard is registered by the mounted player');
console.log('PASS: seven skill tabs precede compact Writing Coach; save feedback shows latest server-confirmed draft state, failures and retry; v14 navigation guard retained.');
