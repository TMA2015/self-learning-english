const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {execFileSync}=require('node:child_process');
const root=path.resolve(__dirname,'..');
execFileSync(process.execPath,['node_modules/typescript/bin/tsc','domain/catalog-taxonomy.ts','--outDir','.sites-runtime/catalog-test','--module','commonjs','--target','es2022','--resolveJsonModule','--esModuleInterop','--skipLibCheck'],{cwd:root,stdio:'inherit'});
fs.writeFileSync(path.join(root,'.sites-runtime/catalog-test/package.json'),'{'+'"type":"commonjs"'+'}');
const {catalogSections}=require('../.sites-runtime/catalog-test/domain/catalog-taxonomy.js');
const source=require('../content/releases/curriculum-1.2.0-production-import.json');
const lessons=source.lessons.map(l=>({id:l.id,title:l.title,module:l.module,cefr:l.cefr_target,minutes:l.estimated_minutes}));
const sequence=source.course.sequence;
const attempts=[{lessonId:'GRA-A1-01',status:'scored'},{lessonId:'GRA-A1-02',status:'started'}];
const grammar=catalogSections(lessons,sequence,attempts,'grammar');
assert(grammar.grouped);
assert.deepEqual(grammar.sections.map(s=>s.id),['GRA-FOUND','GRA-TENSE','GRA-PLACE']);
assert.equal(grammar.sections[0].attempted,1);
assert.deepEqual(new Set(grammar.sections.flatMap(s=>s.lessons.map(l=>l.id))),new Set(lessons.filter(l=>l.module==='grammar').map(l=>l.id)));
const filtered=catalogSections(lessons,sequence,attempts,'grammar','A1');
assert(filtered.grouped);
assert(filtered.sections.every(s=>s.lessons.every(l=>l.cefr==='A1')));
assert(!catalogSections(lessons,sequence,attempts,'listening').grouped);
assert(catalogSections(lessons,sequence,attempts,'reading').grouped);
assert(!catalogSections(lessons,sequence,attempts,'writing','B1').grouped);
const expanded=catalogSections([...lessons,{id:'GRA-A2-99',title:'Future topic',module:'grammar',cefr:'A2',minutes:8}],[...sequence,'GRA-A2-99'],attempts,'grammar');
assert.equal(expanded.sections.at(-1).id,'grammar-additional');
assert.equal(expanded.sections.at(-1).lessons[0].id,'GRA-A2-99');
const all=catalogSections(lessons,sequence,attempts);
assert.deepEqual(all.sections[0].lessons.map(l=>l.id),sequence);
console.log('PASS: Grammar topic sections, independent CEFR filter, grouping thresholds, attempt counts and course order.');
